export const FONT_KEY = 'fuente';
export const FONT_W = 6; // avance por carácter (5 + 1 de separación)
export const FONT_H = 8;
const CHARS = Object.keys(G).join('');
const PER_ROW = 16;

export function bakeFont(scene: Phaser.Scene): void {
  if (scene.cache.bitmapFont.exists(FONT_KEY)) return;
  const rows = Math.ceil(CHARS.length / PER_ROW);
  const canvas = document.createElement('canvas');
  canvas.width = PER_ROW * FONT_W;
  canvas.height = rows * FONT_H;
  const ctx = canvas.getContext('2d')!;
  ctx.fillStyle = '#ffffff';
  [...CHARS].forEach((ch, i) => {
    const gx = (i % PER_ROW) * FONT_W;
    const gy = Math.floor(i / PER_ROW) * FONT_H;
    G[ch].split('|').forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') ctx.fillRect(gx + x, gy + y, 1, 1);
    });
  });
  scene.textures.addCanvas(FONT_KEY, canvas);
  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: FONT_KEY,
    width: FONT_W,
    height: FONT_H,
    chars: CHARS,
    charsPerRow: PER_ROW,
    spacing: { x: 0, y: 0 },
    offset: { x: 0, y: 0 },
    lineSpacing: 1,
  } as unknown as Phaser.Types.GameObjects.BitmapText.RetroFontConfig);
  scene.cache.bitmapFont.add(FONT_KEY, data);
}

const ACCENTS: Record<string, string> = { Á: 'A', É: 'E', Í: 'I', Ó: 'O', Ú: 'U', Ü: 'U', À: 'A', È: 'E' };

/** Pasa el texto al juego de caracteres de la fuente. */
export function fontText(s: string): string {
  return s
    .toUpperCase()
    .replace(/[ÁÉÍÓÚÜÀÈ]/g, (c) => ACCENTS[c])
    .replace(/[—–]/g, '-')
    .split('')
    .map((c) => (c === '\n' || G[c] ? c : '?'))
    .join('');
}

export function textWidth(s: string): number {
  const longest = fontText(s)
    .split('\n')
    .reduce((m, l) => Math.max(m, l.length), 0);
  return longest * FONT_W - 1;
}
